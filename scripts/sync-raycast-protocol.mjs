import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../packages/shared/src/protocol.ts", import.meta.url);
const target = new URL("../extensions/raycast/src/protocol.ts", import.meta.url);
const content = "// Generated by scripts/sync-raycast-protocol.mjs. Edit packages/shared/src/protocol.ts instead.\n" + readFileSync(source, "utf8");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) throw new Error("Raycast protocol snapshot is stale. Run node scripts/sync-raycast-protocol.mjs.");
} else writeFileSync(target, content);
